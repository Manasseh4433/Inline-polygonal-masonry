# frozen_string_literal: true

module PolygonalMasonry
  # Константы конфигурации плагина
  module Config
    # Версия плагина
    VERSION = '1.0.0'
    
    # Параметры генерации полигонов
    # Целевая площадь одного полигона в зависимости от общей площади (в см²)
    # ЗНАЧИТЕЛЬНО УМЕНЬШЕНО для создания большего количества мелких камней
    TARGET_POLYGON_SIZE_SMALL = 15.0 * 15.0      # Для малых поверхностей (< 1 м²) - камни ~15x15 см
    TARGET_POLYGON_SIZE_MEDIUM = 20.0 * 20.0     # Для средних поверхностей (1-10 м²) - камни ~20x20 см
    TARGET_POLYGON_SIZE_LARGE = 25.0 * 25.0      # Для крупных поверхностей (> 10 м²) - камни ~25x25 см
    
    # Минимальная площадь поверхности для обработки (в см²)
    MIN_FACE_AREA = 100.0 * 100.0
    
    # Минимальная площадь полигона (для фильтрации вырожденных)
    # ЗНАЧИТЕЛЬНО УМЕНЬШЕНО чтобы сохранять маленькие граничные камни
    MIN_POLYGON_AREA = 2.0 * 2.0  # Минимум 2×2 см
    
    # Минимальное и максимальное количество полигонов
    MIN_POLYGON_COUNT = 10
    MAX_POLYGON_COUNT = 500  # Увеличено для поддержки больших поверхностей
    
    # Коэффициент минимального расстояния между точками Вороного
    # (в долях от среднего размера полигона)
    MIN_POINT_DISTANCE_RATIO = 0.7  # Уменьшено для более плотной упаковки
    
    # Плотность точек на границе (точек на см)
    BOUNDARY_POINTS_DENSITY = 0.1
    
    # Минимальное расстояние между точками на границе (еще больше уменьшено)
    MIN_BOUNDARY_POINT_DISTANCE = 2.0  # см - для плотного покрытия краёв
    
    # Толерантность для геометрических операций
    TOLERANCE = 0.001
    
    # Максимальное количество попыток для алгоритма Пуассона
    POISSON_MAX_ATTEMPTS = 30
    
    # Пороги площади для выбора целевого размера полигона (в см²)
    SMALL_AREA_THRESHOLD = 10000.0   # 1 м²
    LARGE_AREA_THRESHOLD = 100000.0  # 10 м²
  end
end
